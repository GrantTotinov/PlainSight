// Refreshes src/google-domains.ts from Google's published list of search domains.
// Run manually with `pnpm domains:update`, then review the diff before committing.
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://www.google.com/supported_domains';
const OUT = new URL('../src/google-domains.ts', import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} returned HTTP ${res.status}`);

const domains = [
  ...new Set(
    (await res.text())
      .split('\n')
      .map((line) => line.trim().replace(/^\./, '').toLowerCase())
      .filter((d) => /^google(\.[a-z]{2,3}){1,2}$/.test(d)),
  ),
].sort();

if (!domains.includes('google.com') || domains.length < 100) {
  throw new Error(`Unexpected list (${domains.length} domains), refusing to overwrite.`);
}

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `// Generated by scripts/update-google-domains.ts from ${SOURCE}
// Last updated: ${today}. Do not edit by hand: run \`pnpm domains:update\`.
export const GOOGLE_DOMAINS: readonly string[] = [
${domains.map((d) => `  '${d}',`).join('\n')}
];
`,
);
console.log(`Wrote ${domains.length} domains to src/google-domains.ts`);
